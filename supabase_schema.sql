-- ───────────────────────── EXTENSIONS ───────────────────────
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ═══════════════════════════════════════════════════════════
--  SECTION 1 — CREATE TABLES
-- ═══════════════════════════════════════════════════════════

-- 1. teachers
CREATE TABLE IF NOT EXISTS teachers (
  id            VARCHAR   PRIMARY KEY DEFAULT gen_random_uuid(),
  name          TEXT      NOT NULL,
  subject       TEXT      NOT NULL,
  phone         TEXT,
  email         TEXT,
  salary_type   TEXT      NOT NULL DEFAULT 'fixed',  -- fixed | per_student | percentage
  salary_amount REAL      DEFAULT 0,
  notes         TEXT,
  status        TEXT      NOT NULL DEFAULT 'active',
  created_at    TIMESTAMPTZ DEFAULT NOW()
);

-- 2. subjects
CREATE TABLE IF NOT EXISTS subjects (
  id                  VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  name                TEXT     NOT NULL,
  description         TEXT,
  teacher_id          VARCHAR,
  price               REAL     DEFAULT 0,
  sessions_per_month  INTEGER  DEFAULT 4,
  color               TEXT     DEFAULT '#6366f1',
  created_at          TIMESTAMPTZ DEFAULT NOW()
);

-- 3. groups
CREATE TABLE IF NOT EXISTS groups (
  id           VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  name         TEXT     NOT NULL,
  grade_level  TEXT     NOT NULL,
  section      TEXT     NOT NULL,
  subject      TEXT,
  teacher_id   VARCHAR,
  capacity     INTEGER  DEFAULT 30,
  description  TEXT,
  color        TEXT     DEFAULT '#6366f1',
  created_at   TIMESTAMPTZ DEFAULT NOW()
);

-- 4. students
CREATE TABLE IF NOT EXISTS students (
  id               VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  name             TEXT     NOT NULL,
  guardian_phone   TEXT     NOT NULL,
  guardian_phone2  TEXT,
  address          TEXT,
  code             TEXT     NOT NULL UNIQUE,
  grade_level      TEXT     NOT NULL,
  section          TEXT     NOT NULL,
  group_id         VARCHAR,
  qr_path          TEXT,
  status           TEXT     NOT NULL DEFAULT 'active',  -- active | suspended | overdue | graduated | archived
  created_at       TIMESTAMPTZ DEFAULT NOW()
);

-- 5. enrollments
CREATE TABLE IF NOT EXISTS enrollments (
  id          VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id  VARCHAR  NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  subject_id  VARCHAR,
  teacher_id  VARCHAR,
  group_id    VARCHAR,
  status      TEXT     NOT NULL DEFAULT 'active',  -- active | suspended | completed
  notes       TEXT,
  created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- 6. subscriptions
CREATE TABLE IF NOT EXISTS subscriptions (
  id             VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id     VARCHAR  NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  enrollment_id  VARCHAR,
  subject_id     VARCHAR,
  teacher_id     VARCHAR,
  amount         REAL     NOT NULL,
  paid           REAL     DEFAULT 0,
  start_date     TEXT     NOT NULL,
  end_date       TEXT,
  status         TEXT     NOT NULL DEFAULT 'active',  -- active | paid | overdue | expired
  notes          TEXT,
  created_at     TIMESTAMPTZ DEFAULT NOW()
);

-- 7. sessions
CREATE TABLE IF NOT EXISTS sessions (
  id          VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  name        TEXT     NOT NULL,
  date        TEXT     NOT NULL,
  time        TEXT     NOT NULL,
  duration    INTEGER  NOT NULL,
  group_id    VARCHAR,
  teacher_id  VARCHAR,
  subject_id  VARCHAR,
  status      TEXT     NOT NULL DEFAULT 'scheduled',  -- scheduled | active | completed | cancelled
  created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- 8. attendance
CREATE TABLE IF NOT EXISTS attendance (
  id             VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id     VARCHAR  NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  session_id     VARCHAR  NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
  status         TEXT     NOT NULL,  -- present | absent | late
  time_recorded  TIMESTAMPTZ DEFAULT NOW(),
  scan_method    TEXT     NOT NULL   -- qr | manual | barcode
);

-- 9. grades
CREATE TABLE IF NOT EXISTS grades (
  id               VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id       VARCHAR  NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  subject          TEXT     NOT NULL,
  assessment_type  TEXT     NOT NULL,  -- quiz | exam | homework | midterm | final
  score            INTEGER  NOT NULL,
  total_marks      INTEGER  NOT NULL,
  weight           REAL     DEFAULT 1.0,
  grade            TEXT,
  notes            TEXT,
  sent_to_parent   BOOLEAN  DEFAULT FALSE,
  created_at       TIMESTAMPTZ DEFAULT NOW()
);

-- 10. homework
CREATE TABLE IF NOT EXISTS homework (
  id           VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  title        TEXT     NOT NULL,
  description  TEXT,
  subject      TEXT     NOT NULL,
  group_id     VARCHAR,
  deadline     TEXT     NOT NULL,
  total_marks  INTEGER  DEFAULT 10,
  status       TEXT     NOT NULL DEFAULT 'active',  -- active | closed
  created_at   TIMESTAMPTZ DEFAULT NOW()
);

-- 11. homework_submissions
CREATE TABLE IF NOT EXISTS homework_submissions (
  id           VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  homework_id  VARCHAR  NOT NULL REFERENCES homework(id) ON DELETE CASCADE,
  student_id   VARCHAR  NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  score        INTEGER,
  status       TEXT     NOT NULL DEFAULT 'pending',  -- pending | submitted | graded
  notes        TEXT,
  submitted_at TIMESTAMPTZ DEFAULT NOW()
);

-- 12. finances
CREATE TABLE IF NOT EXISTS finances (
  id          VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id  VARCHAR  NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  type        TEXT     NOT NULL DEFAULT 'subscription',
  amount      REAL     NOT NULL,
  paid        REAL     DEFAULT 0,
  due_date    TEXT     NOT NULL,
  status      TEXT     NOT NULL DEFAULT 'pending',  -- pending | paid | overdue
  notes       TEXT,
  created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- 13. student_notes
CREATE TABLE IF NOT EXISTS student_notes (
  id          VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id  VARCHAR  NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  content     TEXT     NOT NULL,
  type        TEXT     NOT NULL DEFAULT 'general',  -- general | warning | positive | academic
  created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- 14. exams
CREATE TABLE IF NOT EXISTS exams (
  id           VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  title        TEXT     NOT NULL,
  subject      TEXT     NOT NULL,
  group_id     VARCHAR,
  date         TEXT     NOT NULL,
  duration     INTEGER  DEFAULT 60,
  status       TEXT     NOT NULL DEFAULT 'draft',  -- draft | published | completed
  description  TEXT,
  created_at   TIMESTAMPTZ DEFAULT NOW()
);

-- 15. exam_questions
CREATE TABLE IF NOT EXISTS exam_questions (
  id             VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  exam_id        VARCHAR  NOT NULL REFERENCES exams(id) ON DELETE CASCADE,
  question       TEXT     NOT NULL,
  type           TEXT     NOT NULL DEFAULT 'short',  -- mcq | short | long | true_false
  options        TEXT,
  correct_answer TEXT,
  marks          INTEGER  NOT NULL DEFAULT 5,
  order_index    INTEGER  DEFAULT 0
);

-- 16. exam_submissions
CREATE TABLE IF NOT EXISTS exam_submissions (
  id          VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  exam_id     VARCHAR  NOT NULL REFERENCES exams(id) ON DELETE CASCADE,
  student_id  VARCHAR  NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  score       INTEGER,
  status      TEXT     NOT NULL DEFAULT 'pending',
  graded_at   TIMESTAMPTZ,
  created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- 17. expenses
CREATE TABLE IF NOT EXISTS expenses (
  id           VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  category     TEXT     NOT NULL,  -- rent | electricity | salaries | printing | maintenance | other
  amount       REAL     NOT NULL,
  date         TEXT     NOT NULL,
  description  TEXT,
  created_at   TIMESTAMPTZ DEFAULT NOW()
);

-- 18. audit_logs
CREATE TABLE IF NOT EXISTS audit_logs (
  id          VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  entity      TEXT     NOT NULL,
  entity_id   VARCHAR,
  action      TEXT     NOT NULL,  -- create | update | delete
  actor       TEXT     DEFAULT 'admin',
  details     TEXT,
  created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- 19. automation_rules
CREATE TABLE IF NOT EXISTS automation_rules (
  id                VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  name              TEXT     NOT NULL,
  description       TEXT,
  trigger           TEXT     NOT NULL,
  trigger_config    TEXT,
  message_template  TEXT     NOT NULL,
  target_group      TEXT,
  status            TEXT     NOT NULL DEFAULT 'active',
  run_count         INTEGER  DEFAULT 0,
  last_run          TIMESTAMPTZ,
  created_at        TIMESTAMPTZ DEFAULT NOW()
);

-- 20. automation_logs
CREATE TABLE IF NOT EXISTS automation_logs (
  id          VARCHAR  PRIMARY KEY DEFAULT gen_random_uuid(),
  rule_id     VARCHAR  NOT NULL,
  rule_name   TEXT,
  student_id  VARCHAR,
  phone       TEXT,
  message     TEXT,
  status      TEXT     NOT NULL DEFAULT 'sent',
  reason      TEXT,
  created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- ═══════════════════════════════════════════════════════════
--  SECTION 2 — INDEXES (for performance)
-- ═══════════════════════════════════════════════════════════

CREATE INDEX IF NOT EXISTS idx_students_code         ON students(code);
CREATE INDEX IF NOT EXISTS idx_students_status       ON students(status);
CREATE INDEX IF NOT EXISTS idx_students_group_id     ON students(group_id);
CREATE INDEX IF NOT EXISTS idx_enrollments_student   ON enrollments(student_id);
CREATE INDEX IF NOT EXISTS idx_enrollments_teacher   ON enrollments(teacher_id);
CREATE INDEX IF NOT EXISTS idx_attendance_student    ON attendance(student_id);
CREATE INDEX IF NOT EXISTS idx_attendance_session    ON attendance(session_id);
CREATE INDEX IF NOT EXISTS idx_grades_student        ON grades(student_id);
CREATE INDEX IF NOT EXISTS idx_finances_student      ON finances(student_id);
CREATE INDEX IF NOT EXISTS idx_finances_status       ON finances(status);
CREATE INDEX IF NOT EXISTS idx_sessions_date         ON sessions(date);
CREATE INDEX IF NOT EXISTS idx_sessions_status       ON sessions(status);
CREATE INDEX IF NOT EXISTS idx_expenses_date         ON expenses(date);
CREATE INDEX IF NOT EXISTS idx_expenses_category     ON expenses(category);

